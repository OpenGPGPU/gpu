    )

  private def csr(name: String, funct3: String, immediate: Boolean): Rv32Pattern =
    Rv32Pattern(
      name,
      s"?????????????????$funct3?????1110011",
      imm = if (immediate) ImmSel.z else ImmSel.none,
      useImmediate = immediate,
      useRs1 = !immediate,
      writeRd = true,
      csr = true,
      system = true
    )

  private def vectorBranch(name: String, funct3: String, branchOp: Int): Rv32Pattern =
    Rv32Pattern(
      name,
      s"?????????????????$funct3?????1011011",
      branch = branchOp,
      imm = ImmSel.b,
