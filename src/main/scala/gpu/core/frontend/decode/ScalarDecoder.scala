object BranchOp {
  val width = 3
  val none = 0.U(width.W)
  val eq   = 1.U(width.W)
  val ne   = 2.U(width.W)
  val lt   = 3.U(width.W)
  val ge   = 4.U(width.W)
  val ltu  = 5.U(width.W)
  val geu  = 6.U(width.W)
}

private object ImmSel {
  val width = 3
  val none = 0
  val i = 1
  val s = 2
  val b = 3
  val u = 4
  val j = 5
  val z = 6
}

class DecodeSignals extends Bundle {
  val legal = Bool()
  val rs1 = UInt(5.W)
  val rs2 = UInt(5.W)
  val rd = UInt(5.W)
  val immediate = UInt(32.W)

  val aluOp = UInt(AluOp.width.W)
  val branchOp = UInt(BranchOp.width.W)
  val useImmediate = Bool()
  val usePc = Bool()
  val useRs1 = Bool()
  val useRs2 = Bool()
  val writeRd = Bool()
  val memoryRead = Bool()
  val memoryWrite = Bool()
  val jump = Bool()
  val multiply = Bool()
  val divide = Bool()
  val atomic = Bool()
  val atomicOp = UInt(4.W)
  val csr = Bool()
  val system = Bool()
  val fence = Bool()
  val barrier = Bool()
  val vectorBranch = Bool()
  val join = Bool()
  val cease = Bool()
}

/** One row in the RV32I decode database.
  *
  * This follows opengpu's CoreDecoder structure: instruction metadata is kept
  * in DecodePattern objects and each control signal is generated by a
  * DecodeField. Adding an instruction therefore means adding a table row, not
  * another branch to the decoder circuit.
  */
private case class Rv32Pattern(
  name: String,
  encoding: String,
  alu: Int = 0,
  branch: Int = 0,
  imm: Int = 0,
  useImmediate: Boolean = false,
  usePc: Boolean = false,
  useRs1: Boolean = false,
  useRs2: Boolean = false,
  writeRd: Boolean = false,
  memoryRead: Boolean = false,
  memoryWrite: Boolean = false,
  jump: Boolean = false,
  multiply: Boolean = false,
  divide: Boolean = false,
  atomic: Boolean = false,
  atomicOp: Int = 0,
  csr: Boolean = false,
  system: Boolean = false,
  fence: Boolean = false,
  barrier: Boolean = false,
  vectorBranch: Boolean = false,
  join: Boolean = false,
  cease: Boolean = false
) extends DecodePattern {
  override def bitPat: BitPat = BitPat("b" + encoding)
}

private abstract class UIntField(
  override val name: String,
  width: Int,
  defaultValue: Int = 0
) extends DecodeField[Rv32Pattern, UInt] {
  override def chiselType: UInt = UInt(width.W)
  override def default: BitPat = BitPat(defaultValue.U(width.W))
  protected def value(pattern: Rv32Pattern): Int
  override def genTable(pattern: Rv32Pattern): BitPat = BitPat(value(pattern).U(width.W))
}

private abstract class BoolField(override val name: String)
    extends BoolDecodeField[Rv32Pattern] {
  override def default: BitPat = n
  protected def value(pattern: Rv32Pattern): Boolean
  override def genTable(pattern: Rv32Pattern): BitPat = if (value(pattern)) y else n
}

private object Rv32Decode {
  object Legal extends BoolField("legal") {
    override protected def value(pattern: Rv32Pattern): Boolean = true
