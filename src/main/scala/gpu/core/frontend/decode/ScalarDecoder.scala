    override protected def value(pattern: Rv32Pattern): Boolean = pattern.join
  }
  object Cease extends BoolField("cease") {
    override protected def value(pattern: Rv32Pattern): Boolean = pattern.cease
  }

  private def op(name: String, funct3: String, alu: Int): Rv32Pattern =
    Rv32Pattern(name, s"0000000??????????$funct3?????0110011",
      alu = alu, useRs1 = true, useRs2 = true, writeRd = true)

  private def opAlt(name: String, funct3: String, alu: Int): Rv32Pattern =
    Rv32Pattern(name, s"0100000??????????$funct3?????0110011",
      alu = alu, useRs1 = true, useRs2 = true, writeRd = true)

  private def opImm(name: String, funct3: String, alu: Int): Rv32Pattern =
    Rv32Pattern(
      name,
      s"?????????????????$funct3?????0010011",
      alu = alu,
      imm = ImmSel.i,
      useImmediate = true,
      useRs1 = true,
      writeRd = true
    )

  private def load(name: String, funct3: String): Rv32Pattern =
    Rv32Pattern(
      name,
      s"?????????????????$funct3?????0000011",
      imm = ImmSel.i,
      useImmediate = true,
      useRs1 = true,
      writeRd = true,
      memoryRead = true
    )

  private def store(name: String, funct3: String): Rv32Pattern =
    Rv32Pattern(
      name,
      s"?????????????????$funct3?????0100011",
      imm = ImmSel.s,
      useImmediate = true,
      useRs1 = true,
      useRs2 = true,
      memoryWrite = true
    )

  private def branch(name: String, funct3: String, branchOp: Int): Rv32Pattern =
    Rv32Pattern(
      name,
      s"?????????????????$funct3?????1100011",
      branch = branchOp,
      imm = ImmSel.b,
      useRs1 = true,
      useRs2 = true
    )

  private def mulDiv(name: String, funct3: String, isDivide: Boolean): Rv32Pattern =
    Rv32Pattern(
      name,
      s"0000001??????????$funct3?????0110011",
      useRs1 = true,
      useRs2 = true,
      writeRd = true,
      multiply = !isDivide,
      divide = isDivide
    )

  private def amo(name: String, funct5: String, operation: Int): Rv32Pattern =
    Rv32Pattern(
      name,
      s"$funct5????????????010?????0101111",
      useRs1 = true,
      useRs2 = true,
      writeRd = true,
      memoryRead = true,
