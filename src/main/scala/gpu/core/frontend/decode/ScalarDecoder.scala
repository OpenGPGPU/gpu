/** Table-driven combinational decoder for the RV32I subset used by GPU lanes. */
class RiscVDecoder extends Module {
  val io = IO(new Bundle {
    val instruction = Input(UInt(32.W))
    val decoded = Output(new DecodeSignals)
  })

  val instruction = io.instruction
  val decoded = Rv32Decode.table.decode(instruction)
  val immediateSelection = decoded(Rv32Decode.Immediate)

  val immI = Cat(Fill(20, instruction(31)), instruction(31, 20))
  val immS = Cat(Fill(20, instruction(31)), instruction(31, 25), instruction(11, 7))
  val immB = Cat(Fill(19, instruction(31)), instruction(31), instruction(7),
    instruction(30, 25), instruction(11, 8), 0.U(1.W))
  val immU = Cat(instruction(31, 12), 0.U(12.W))
  val immJ = Cat(Fill(11, instruction(31)), instruction(31), instruction(19, 12),
    instruction(20), instruction(30, 21), 0.U(1.W))
  val immZ = Cat(0.U(27.W), instruction(19, 15))

  io.decoded.legal := decoded(Rv32Decode.Legal)
  io.decoded.rs1 := instruction(19, 15)
  io.decoded.rs2 := instruction(24, 20)
  io.decoded.rd := instruction(11, 7)
  io.decoded.immediate := MuxLookup(immediateSelection, 0.U)(Seq(
    ImmSel.i.U -> immI,
    ImmSel.s.U -> immS,
    ImmSel.b.U -> immB,
    ImmSel.u.U -> immU,
    ImmSel.j.U -> immJ,
    ImmSel.z.U -> immZ
  ))
  io.decoded.aluOp := decoded(Rv32Decode.Alu)
  io.decoded.branchOp := decoded(Rv32Decode.Branch)
  io.decoded.useImmediate := decoded(Rv32Decode.UseImmediate)
  io.decoded.usePc := decoded(Rv32Decode.UsePc)
  io.decoded.useRs1 := decoded(Rv32Decode.UseRs1)
  io.decoded.useRs2 := decoded(Rv32Decode.UseRs2)
  io.decoded.writeRd := decoded(Rv32Decode.WriteRd)
  io.decoded.memoryRead := decoded(Rv32Decode.MemoryRead)
  io.decoded.memoryWrite := decoded(Rv32Decode.MemoryWrite)
  io.decoded.jump := decoded(Rv32Decode.Jump)
  io.decoded.multiply := decoded(Rv32Decode.Multiply)
  io.decoded.divide := decoded(Rv32Decode.Divide)
  io.decoded.atomic := decoded(Rv32Decode.Atomic)
  io.decoded.atomicOp := decoded(Rv32Decode.AtomicOp)
  io.decoded.csr := decoded(Rv32Decode.Csr)
  io.decoded.system := decoded(Rv32Decode.System)
  io.decoded.fence := decoded(Rv32Decode.Fence)
  io.decoded.barrier := decoded(Rv32Decode.Barrier)
  io.decoded.vectorBranch := decoded(Rv32Decode.VectorBranch)
  io.decoded.join := decoded(Rv32Decode.Join)
  io.decoded.cease := decoded(Rv32Decode.Cease)
}

